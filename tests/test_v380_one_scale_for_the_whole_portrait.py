"""v380: one scale for the whole portrait (A_FOCUS_WEARS_GOLD too). All data is synthetic.

Owner observation (2026-09-30), looking at v378 on his vault: "the intended
surface for Nostalgia is three times the radius of [my brother] ... the
biggest things would be my dad and my mom, to tell a story about myself ...
why is Forgiveness two or three times the size of Katie?" v378 calibrated
PER TYPE, so the best-told theme ("Family", tagged in nearly every source)
set every theme's target and themes outsized the people. v380 calibrates the
whole graph on ONE scale anchored on people (the best-told parent/spouse/
partner sits on its target) and sizes every other type with ``type_scale``
(theme 0.3 of a parent). Told can exceed target: ``over`` is emitted, the
drawing marks it, doctor lists the most over-told. v378's behaviour is one
config line away (``calibration.mode: per_type``) and reproduces its numbers
byte-for-byte (``goldens/portrait_targets_v378_per_type.json``, generated by
the v378 code on this same fixture).

Owner addition (same day): "a golden orb around the intended size" for the
entities picked to be focuses, and projects distinct — A_FOCUS_WEARS_GOLD:
a static gold halo outside the target ring on every active Focus, a
second-colour halo on every project, ``focus``/``project`` flags on nodes.

Fixture: the v378 real-shaped vault (``test_v378_the_ring_is_a_target``),
then a theme page, "Family", tagged by three classified sources.
"""

